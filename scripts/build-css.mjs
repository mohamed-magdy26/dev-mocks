import { readFileSync, writeFileSync } from 'node:fs'
import postcss from 'postcss'
import tailwindcss from 'tailwindcss'
import config from '../tailwind.config.js'

const input = 'src/runtime/panel/panel.css'
const output = 'src/runtime/panel/styles.generated.ts'

// rem follows the host page's <html> font size, which some apps change, so every rem becomes px (1rem = 16px).
const remToPx = {
  postcssPlugin: 'rem-to-px',
  Declaration(declaration) {
    declaration.value = declaration.value.replace(/(-?\d*\.?\d+)rem\b/g, (_, value) => `${Number(value) * 16}px`)
  },
}

const result = await postcss([tailwindcss(config), remToPx]).process(readFileSync(input, 'utf8'), { from: input })
writeFileSync(output, `// Generated by scripts/build-css.mjs. Do not edit.\nexport const css = ${JSON.stringify(result.css)}\n`)
console.log(`✔ ${output}: ${result.css.length} characters of CSS`)
